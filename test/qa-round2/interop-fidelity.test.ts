  // ── 4. QA-09 D12 / QA-05 F9 (MAJOR, §27/§35) ────────────────────────────────────────────
  test('QA-09 D12 / QA-05 F9 (§27, §35): re-importing an edited export over the workspace that still holds the original — `--merge-strategy ask` must REPORT the conflict (conflicts[] populated per §35) and must not merge', () => {
    const ws = makeWorkspace('d12-ask-edited-export');
    // Workspace holding the original: 02-authentication.md with the cans version of the node.
    putFile(ws, join('cans', '02-authentication.md'), '- Sessions\n  - Expire after 24 hours\n');
    const ex = runCli(['export', 'opml', '--json'], ws);
    expect(ex.exit).toBe(0);
    const expDir = join(ws, 'cans-export', 'opml');
    const expFile = findFileContaining(expDir, 'Expire after 24 hours');
    expect(expFile, 'setup: exported OPML containing the node must exist').not.toBeNull();
    // Hand-edit the EXPORTED source: 24 → 72 hours (the human/external change).
    writeFileSync(expFile!, readFileSync(expFile!, 'utf-8').replace(/24 hours/g, '72 hours'));
    // Re-import the edited export over the workspace with ask.
    const src = relative(ws, expFile!);
    const r = runCli(['import', 'opml', src, '--merge-strategy', 'ask', '--json'], ws);
    expect(r.exit).toBe(0);
    const j = JSON.parse(r.out);
    // §27: ask = "report conflicts, don't merge". The workspace still holds "Expire after
    // 24 hours" while the import brings "Expire after 72 hours" — a machine consumer MUST be
    // able to learn that a conflict happened. Current: conflicts:[] + a silently forked file.
    expect(Array.isArray(j.conflicts)).toBe(true);
    expect(j.conflicts.length, 'ask must report the conflict (§27/§35)').toBeGreaterThan(0);
    // §35 conflicts[] entry shape: { file, line, cansVersion, importVersion, resolution }.
    const c = j.conflicts[0];
    expect(typeof c.file).toBe('string');
    expect((c.file as string).length).toBeGreaterThan(0);
    expect(typeof c.line).toBe('number');
    expect(c.cansVersion).toContain('24 hours'); // cans version = the workspace's text
    expect(c.importVersion).toContain('72 hours'); // import version = the edited export
    expect(typeof c.resolution === 'string' && (c.resolution as string).length > 0).toBe(true);
    // Don't merge honored: the CANS file named by the report still holds the cans version,
    // and the import version was not written into it.
    const cansFile = join(ws, 'cans', c.file);
    expect(existsSync(cansFile)).toBe(true);
    const content = readFileSync(cansFile, 'utf-8');
    expect(content).toContain('Expire after 24 hours');
    expect(content).not.toContain('72 hours');
  });

  // ── 5. CONTROL (expected PASS) — isolates finding 4 to the export→edit→import flow ──────
