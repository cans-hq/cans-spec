function runCli(args: string[], cwd: string): { exit: number | null; out: string; err: string } {
  const env = { ...process.env, CANS_ROOT: '' } as Record<string, string>; // isolation: scratch cwd decides the workspace
  const p = Bun.spawnSync(['bun', 'run', CLI, ...args], { cwd, env, stdout: 'pipe', stderr: 'pipe' });
  return { exit: p.exitCode, out: p.stdout.toString(), err: p.stderr.toString() };
}

/** Fresh `cans init` workspace under BASE/<name>; `bare` keeps it to 00-overview + _rules.yaml. */
function makeWorkspace(name: string, bare = true): string {
  const dir = join(BASE, name);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const r = runCli(['init', ...(bare ? ['--bare'] : [])], dir);
  if (r.exit !== 0) throw new Error(`setup: cans init failed in ${dir}: ${r.out}${r.err}`);
  return dir;
}

/** Write a file inside the scratch workspace (dirs created as needed). */
function putFile(ws: string, rel: string, content: string): void {
  const p = join(ws, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content);
}

/** Concatenation of every file under root (recursive) — overflow files included. */
function readAllUnder(root: string): string {
  const out: string[] = [];
  const walk = (d: string): void => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.isFile()) out.push(readFileSync(p, 'utf-8'));
    }
  };
  if (existsSync(root)) walk(root);
  return out.join('\n');
}

/** First file under root whose basename equals `name` (searches subdirs, e.g. _tasks/). */
function findFileNamed(root: string, name: string): string | null {
  const walk = (d: string): string | null => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) {
        const hit = walk(p);
        if (hit) return hit;
      } else if (e.isFile() && e.name === name) return p;
    }
    return null;
  };
  return existsSync(root) ? walk(root) : null;
}

/** First file in `dir` whose content contains `needle`. */
function findFileContaining(dir: string, needle: string): string | null {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isFile() && readFileSync(p, 'utf-8').includes(needle)) return p;
  }
  return null;
}

